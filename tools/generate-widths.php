<?php
/**
 * Regenerates src/Surface/Width.php: the column width of every Unicode code point, the way
 * wcwidth() and xterm count it. Run with ext-intl: php tools/generate-widths.php
 *
 *   0  combining marks (Mn, Me), format characters (Cf, except U+00AD), Hangul medial and
 *      final jamo (U+1160-U+11FF, U+D7B0-U+D7FF), zero width space
 *   2  East Asian Wide and Fullwidth (this includes the emoji with emoji presentation)
 *   1  everything else
 */
if (!class_exists(IntlChar::class)) {
    fwrite(STDERR, "ext-intl is required to generate the width table\n");
    exit(1);
}

$width = static function (int $cp): int {
    if ($cp === 0xAD) {
        return 1;
    }
    if (($cp >= 0x1160 && $cp <= 0x11FF) || ($cp >= 0xD7B0 && $cp <= 0xD7FF) || $cp === 0x200B) {
        return 0;
    }
    $cat = IntlChar::charType($cp);
    if ($cat === IntlChar::CHAR_CATEGORY_NON_SPACING_MARK || $cat === IntlChar::CHAR_CATEGORY_ENCLOSING_MARK
        || $cat === IntlChar::CHAR_CATEGORY_FORMAT_CHAR) {
        return 0;
    }
    $eaw = IntlChar::getIntPropertyValue($cp, IntlChar::PROPERTY_EAST_ASIAN_WIDTH);
    if ($eaw === IntlChar::EA_WIDE || $eaw === IntlChar::EA_FULLWIDTH) {
        return 2;
    }
    return 1;
};

$ranges = [0 => [], 2 => []];
$start = null;
$current = 1;
for ($cp = 0xA0; $cp <= 0x110000; $cp++) {
    $w = $cp === 0x110000 ? 1 : ($cp >= 0xD800 && $cp <= 0xDFFF ? 1 : $width($cp));
    if ($w !== $current) {
        if ($current !== 1) {
            $ranges[$current][] = [$start, $cp - 1];
        }
        $start = $cp;
        $current = $w;
    }
}

$format = static function (array $list): string {
    $out = [];
    foreach ($list as [$a, $b]) {
        $out[] = sprintf('[0x%X, 0x%X]', $a, $b);
    }
    return implode(",\n        ", $out);
};

$unicode = implode('.', array_slice(IntlChar::getUnicodeVersion(), 0, 2));
$icu = INTL_ICU_VERSION;
$code = <<<PHP
<?php
// Generated by tools/generate-widths.php from Unicode $unicode (ICU $icu). Do not edit.

namespace phasync\Tui\Surface;

/**
 * @internal Column widths of code points, as wcwidth() counts them: 0 for combining and format
 * characters, 2 for East Asian Wide and Fullwidth, 1 otherwise.
 */
final class Width
{
    /** @var list<array{int,int}> */
    public const ZERO = [
        {$format($ranges[0])},
    ];

    /** @var list<array{int,int}> */
    public const WIDE = [
        {$format($ranges[2])},
    ];

    /** @var array<int,int> */
    private static array \$cache = [];

    /** The number of columns code point \$cp occupies: 0, 1 or 2. */
    public static function of(int \$cp): int
    {
        if (\$cp < 0x300) {
            return \$cp === 0xAD || \$cp >= 0x20 ? 1 : 0;
        }
        return self::\$cache[\$cp] ??= (self::search(self::ZERO, \$cp) ? 0 : (self::search(self::WIDE, \$cp) ? 2 : 1));
    }

    /** @param list<array{int,int}> \$ranges */
    private static function search(array \$ranges, int \$cp): bool
    {
        \$lo = 0;
        \$hi = \count(\$ranges) - 1;
        while (\$lo <= \$hi) {
            \$mid = (\$lo + \$hi) >> 1;
            if (\$cp < \$ranges[\$mid][0]) {
                \$hi = \$mid - 1;
            } elseif (\$cp > \$ranges[\$mid][1]) {
                \$lo = \$mid + 1;
            } else {
                return true;
            }
        }
        return false;
    }
}

PHP;
file_put_contents(__DIR__ . '/../src/Surface/Width.php', $code);
echo "wrote src/Surface/Width.php (", count($ranges[0]), " zero-width ranges, ", count($ranges[2]), " wide ranges)\n";
